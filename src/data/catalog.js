const rp = value => Math.round(value / 1000) * 1000

function googleImageSearch(name) {
  return `https://www.google.com/search?tbm=isch&q=${encodeURIComponent(name)}`
}

function searchThumbnail(name, category, index) {
  const host = (index % 4) + 1
  const suffix = category === 'makanan' ? ' makanan Indonesia' : ' official product'
  return `https://tse${host}.mm.bing.net/th?q=${encodeURIComponent(name + suffix)}&w=900&h=900&c=7&rs=1&p=0`
}

function makeProduct({ id, name, category, index, min, max }) {
  const span = Math.max(1000, max - min)
  const price = rp(min + ((index * 131071) % span))
  const rating = (4 + ((index * 7) % 10) / 10).toFixed(1)
  const reviewCount = 180 + ((index * 137) % 14800)
  const badges = ['BEST', 'HOT', 'VIRAL', 'HEMAT', 'PILIHAN']

  return {
    id,
    name,
    category,
    price,
    rating,
    reviewCount,
    badge: badges[index % badges.length],
    image: searchThumbnail(name, category, index),
    imageSearch: googleImageSearch(name),
  }
}

function buildCatalog(names, category, prefix, min, max) {
  return names.slice(0, 100).map((name, index) => makeProduct({
    id: `${prefix}-${String(index + 1).padStart(3, '0')}`,
    name,
    category,
    index,
    min,
    max,
  }))
}

